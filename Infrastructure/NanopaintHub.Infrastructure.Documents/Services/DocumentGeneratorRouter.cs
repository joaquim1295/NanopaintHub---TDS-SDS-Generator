using System.Threading.Tasks;
using Microsoft.Extensions.Options;
using NanopaintHub.Application.Contracts;
using NanopaintHub.Application.Tds;
using NanopaintHub.Domain.Entities;
using NanopaintHub.Infrastructure.Documents.DependencyInjection;

namespace NanopaintHub.Infrastructure.Documents.Services;

public class DocumentGeneratorRouter : IDocumentGeneratorService
{
    private readonly PdfGeneratorOptions _options;
    private readonly QuestPdfDocumentGeneratorService _questPdfGenerator;
    private readonly DocumentGeneratorService _puppeteerGenerator;

    public DocumentGeneratorRouter(
        IOptions<PdfGeneratorOptions> options,
        QuestPdfDocumentGeneratorService questPdfGenerator,
        DocumentGeneratorService puppeteerGenerator)
    {
        _options = options.Value;
        _questPdfGenerator = questPdfGenerator;
        _puppeteerGenerator = puppeteerGenerator;
    }

    public Task<byte[]> GenerateTdsAsync(Product product, DocumentTemplate template, TestBatch? testBatch = null, PdfGenerationSettings? settings = null)
    {
        if (_options.Engine == "QuestPDF")
        {
            return _questPdfGenerator.GenerateTdsAsync(product, template, testBatch, settings);
        }
        else
        {
            return _puppeteerGenerator.GenerateTdsAsync(product, template, testBatch, settings);
        }
    }

    public Task<byte[]> GenerateSdsAsync(Product product, DocumentTemplate template, PdfGenerationSettings? settings = null)
    {
        // QuestPDF for SDS is not implemented yet, default to legacy
        return _puppeteerGenerator.GenerateSdsAsync(product, template, settings);
    }

    public Task<string> GenerateHtmlAsync(Product product, DocumentTemplate template, bool asEditorPreview = false, TestBatch? testBatch = null)
    {
        // HTML is only generated by legacy
        return _puppeteerGenerator.GenerateHtmlAsync(product, template, asEditorPreview, testBatch);
    }

    public Task<byte[]> GeneratePdfFromHtmlAsync(string htmlContent, DocumentTemplate template, PdfGenerationSettings? settings = null)
    {
        // PDF from HTML is only legacy
        return _puppeteerGenerator.GeneratePdfFromHtmlAsync(htmlContent, template, settings);
    }
}
